package org.vs.valentine.cards.model.universal;

/**
 * Types of Valentine cards.
 */
public enum CardType {
    /**
     * Romantic card for lovers
     */
    ROMANTIC,

    /**
     * Friendly card for friends
     */
    FRIENDLY,

    /**
     * Family card for family members
     */
    FAMILY,

    /**
     * Secret admirer card
     */
    SECRET_ADMIRER,

    /**
     * Custom/other type
     */
    CUSTOM
}
